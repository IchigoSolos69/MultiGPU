    await page.goto(base+'/#new');
    assert.equal(await page.getByLabel('Run name',{exact:true}).inputValue(),completedName,'Navigation lost the draft');
    await advanceToCompute();
    await page.getByLabel('Primary resource',{exact:true}).selectOption('colab');
    await page.getByLabel('Add fallback resource',{exact:true}).selectOption('local');
    await page.getByRole('button',{name:'Add fallback',exact:true}).click();
    await page.getByLabel('Add fallback resource',{exact:true}).selectOption('modal');
    await page.getByRole('button',{name:'Add fallback',exact:true}).click();
