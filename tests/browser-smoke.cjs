    await page.getByRole('button',{name:'Resume training',exact:true}).waitFor({timeout:30000});
    await page.getByRole('button',{name:'Repeat settings',exact:true}).click();
    await page.waitForURL('**/#new');
    await advanceToTraining();
    await page.getByLabel('Run name',{exact:true}).fill('UI acceptance guided');
    await advanceToCompute();
    await page.getByLabel('Primary resource',{exact:true}).selectOption('colab');
