    const notebook=page.waitForEvent('download');
    await page.getByRole('button',{name:'Download training notebook',exact:true}).click();
    await (await notebook).saveAs(path.join(out,'training.ipynb'));
    await page.locator('#guided-import').evaluate(el=>el.open=true);
    await waitStep('Bring your results back');
    await page.getByLabel('Downloaded output folder or ZIP').fill(path.join(out,'does-not-exist.zip'));
    await page.getByRole('button',{name:'Preview & verify results',exact:true}).click();
    await page.waitForFunction(()=>!!document.querySelector('#job-action-error')?.textContent.trim());
    assert.equal(await page.getByRole('button',{name:'Import verified results',exact:true}).count(),0);
    await page.goto(completedUrl);
    await page.getByRole('button',{name:'Archive run',exact:true}).click();
    await page.getByRole('button',{name:'Restore from archive',exact:true}).waitFor();
    await page.locator('#navigation a[href="#jobs"]').click();
    await page.getByLabel('Search training runs',{exact:true}).fill(completedName);
    assert.equal(await page.locator('.job-row').count(),0);
    await page.getByRole('checkbox',{name:'Include archived'}).check();
    assert.equal(await page.locator('.job-row').count(),1);
    // Skip link keeps the current route and gives main a keyboard focus target.
    const routeBefore=page.url();
    await page.locator('.skip-link').focus();await page.keyboard.press('Enter');
    assert.equal(page.url(),routeBefore);assert.equal(await page.locator('#main').evaluate(e=>e===document.activeElement),true);
    await page.goto(completedUrl);
    await page.setViewportSize({width:390,height:844});
    await page.locator('.chart').waitFor();
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Phone job layout overflowed');
    await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
    await page.locator('#toast').waitFor({state:'hidden',timeout:10000});
    await page.screenshot({path:path.join(out,'completed-mobile.png'),fullPage:true});
    await page.getByRole('button',{name:'Open navigation',exact:true}).click();
