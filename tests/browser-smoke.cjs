    assert(await page.getByRole('checkbox',{name:'Use only free allowance'}).isChecked(),'Paid authority restored on startup');
    assert((await page.locator('.fallback-list li').first().textContent()).includes('Modal'),'Fallback order lost');
    await page.getByLabel('Primary resource',{exact:true}).selectOption('local');
    await removeFallbacks();
    await preview();
    await page.getByRole('button',{name:'Start training',exact:true}).waitFor();
